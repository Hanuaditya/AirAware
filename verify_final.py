import pandas as pd, numpy as np
df = pd.read_csv('data/processed/aqi_14day.csv')
print('=== FINAL VERIFICATION: Silk Board 14-Day Primary Dataset ===')
print('Station:', df['station'].iloc[0])
print('Window:', df['date'].min(), 'to', df['date'].max())
print()
print('AQI (derived):')
mean_aqi = df['aqi_derived'].mean()
max_aqi  = df['aqi_derived'].max()
max_date = df.loc[df['aqi_derived'].idxmax(), 'date']
min_aqi  = df['aqi_derived'].min()
min_date = df.loc[df['aqi_derived'].idxmin(), 'date']
med_aqi  = df['aqi_derived'].median()
std_aqi  = df['aqi_derived'].std()
print(f'  Mean:    {mean_aqi:.2f}')
print(f'  Max:     {max_aqi:.1f} on {max_date}')
print(f'  Min:     {min_aqi:.1f} on {min_date}')
print(f'  Median:  {med_aqi:.2f}')
print(f'  Std Dev: {std_aqi:.2f}')
print()
print('PM2.5 (ug/m3):')
print('  Mean:', round(df['pm25'].mean(), 2), '| Max:', round(df['pm25'].max(), 2), '| Min:', round(df['pm25'].min(), 2))
print('PM10 (ug/m3):')
print('  Mean:', round(df['pm10'].mean(), 2), '| Max:', round(df['pm10'].max(), 2), '| Min:', round(df['pm10'].min(), 2))
print()
print('Dominant Pollutant:', df['dominant_pollutant'].value_counts().to_dict())
print()
print('Category Distribution:')
for cat, cnt in df['category'].value_counts().items():
    print(f'  {cat}: {cnt} days ({cnt/14*100:.1f}%)')
print()
print('Regulatory Exceedances:')
print('  NAAQS PM10 (>100):', df['exceed_naaqs_pm10'].sum(), '/14 days')
print('  WHO   PM10 (>45): ', df['exceed_who_pm10'].sum(), '/14 days')
print('  NAAQS PM2.5 (>60):', df['exceed_naaqs_pm25'].sum(), '/14 days')
print('  WHO   PM2.5 (>15):', df['exceed_who_pm25'].sum(), '/14 days')
print()
r = df['pm_ratio'].dropna()
print('PM2.5/PM10 Ratio:', round(r.mean(), 3), '| Range:', round(r.min(), 3), '-', round(r.max(), 3))

